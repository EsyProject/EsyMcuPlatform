#ifndef ESY_ATOMIC_DEFS_H
#define ESY_ATOMIC_DEFS_H

/**
 * @file esy_atomic_defs.h
 * @brief Compile-time contract for concurrent task/ISR 32-bit C11 atomics.
 *
 * Native builds require always-lock-free integer atomics. Integration may select
 * ESY_ATOMIC_IRQ_SPINLOCK_BACKEND only with a verified IRQ-masked spinlock
 * provider. That backend can briefly contend with another core; callers must
 * never hold its lock across callbacks, waits, allocation or logging. Maskable
 * ISR callers are supported; NMI/fault callers and concurrent core reset/halt
 * are excluded. Hardware/OS headers and runtime operations do not belong here.
 * The backend definition is generated by build integration, not a feature switch.
 */

#if !defined(__cplusplus)
#include <stdint.h>
#include <stdatomic.h>

_Static_assert(sizeof(unsigned int) == sizeof(uint32_t),
               "the atomic contract requires 32-bit unsigned integers");
#if !defined(ESY_ATOMIC_IRQ_SPINLOCK_BACKEND)
_Static_assert(ATOMIC_INT_LOCK_FREE == 2,
               "task/ISR atomics require an always-lock-free or verified IRQ-spinlock backend");
#else
_Static_assert(ESY_ATOMIC_IRQ_SPINLOCK_BACKEND == 1,
               "invalid IRQ-spinlock backend capability");
#endif
#endif

#endif
